def t_rq1(perf, w, inputs):
    p = perf[perf["workload"] == w].set_index(["detector", "metric"])
    rows = []
    for d in PANEL + ["RF", "RuleBased", "EWMA", "\\midrule", "TimeOnly", "PhasePosition", "AlwaysFire"]:
        if d == "\\midrule":
            rows.append(d)
            continue
        g = lambda m, k="pooled_mean": p.loc[(d, m), k]
        rows.append(" & ".join([NAMES[d], f3(g("pooled_auc", "c1_mean")),
                                ci(g("pooled_auc"), g("pooled_auc", "pooled_lo"), g("pooled_auc", "pooled_hi")),
                                f3(g("within_run_auc")), f3(g("within_run_pc")), f3(g("r1_placebo")),
                                f"{f3(g('pr_auc'))} ({f3(g('prevalence'))})",
                                f"{f3(g('f1_f1opt'))} ({f3(g('always_fire_f1_f1opt'))})"]))
    return table(f"tab_rq1_{w}.tex", f"{WL[w]} detectors at the 30 s anchor, with the three diagnostic rows.",
                 f"tab:rq1-{w}", "llllllll", "Detector & Pooled AUC, c1 & Pooled AUC, c2+c3 & Within-run AUC & "
                 "Within-run, corrected & R1 placebo & PR-AUC (prev.) & F1 (always-fire)", rows,
                 "c1 is campaign 1 under the frozen configuration. Other columns pool campaigns 2 and 3 (20 folds) "
                 "with 95\\% intervals for pooled AUC. Corrected is within-run AUC minus the sham placebo, so chance "
                 "is 0. The R1 placebo ranks each run's 5 late pre-fault windows against its 5 early ones, chance 0.5. "
                 "F1 at the F1-optimal threshold on cal. Sequence models score fewer windows, so their prevalence is "
                 "higher.", inputs, wide=True)


def t_oper(oper, b, inputs):
    rows = []
    o = oper.set_index(["workload", "detector", "metric"])
    for d in PANEL + ["RF", "RuleBased", "EWMA", "\\midrule", "TimeOnly", "PhasePosition"]:
        if d == "\\midrule":
            rows.append(d)
            continue
        cells = [NAMES[d]]
        for w in ("ecommerce", "iot"):
            g = lambda m: o["pooled_mean"].get((w, d, f"{m}_fpb_{b}"), float("nan"))   # PhasePosition has no trailing value
            cells += [f3(g("recall")), f3(g("precision")), f3(g("fpr")), f"{g('fa_per_h'):.1f}",
                      ("n/a" if pd.isna(g("trailing_fa_per_h")) else f"{g('trailing_fa_per_h'):.1f}"),
                      f3(g("episode_rate")), f3(g("sham_episode"))]
        rows.append(" & ".join(cells))
    pct = f"{100 * float(b):.0f}\\%"
    return table(f"tab_oper_b{b}.tex", f"Operating point at a {pct} false-positive budget set on cal NORMAL windows "
                 "without labels.", f"tab:oper-{b}", "l" + "l" * 14,
                 "& \\multicolumn{7}{c}{E-commerce} & \\multicolumn{7}{c}{IoT} \\\\ Detector & Rec. & Prec. & FPR & "
                 "FA/h & FA/h tr. & Episode & Sham ep. & Rec. & Prec. & FPR & FA/h & FA/h tr. & Episode & Sham ep.",
                 rows, "Means pooled over campaigns 2 and 3. FPR is realised on all test negatives, including RECOVERY. "
                 "FA/h counts alert onsets per hour of negative time on the test block and on the trailing baseline "
                 "(tr.). Episode is the share of fault runs with an alert in the labelled span, sham ep. the share of "
                 "shams with one.", inputs, wide=True)


def t_latency(lat, inputs):
    rows = []
    l_ = lat[(lat["scope"] == "all faults") & (lat["set"] == "pooled")].set_index(["workload", "detector", "budget"])
    for d in PANEL + ["RF", "RuleBased", "EWMA"]:
        cells = [NAMES[d]]
        for w in ("ecommerce", "iot"):
            for b in ("fpb_0.01", "fpb_0.05"):
                r = l_.loc[(w, d, b)]
                med = "n/a" if pd.isna(r["km_median_s"]) else f"{r['km_median_s']:.0f}"
                cells += [f"{100 * r['detection_rate']:.0f}\\%", f"{r['rmst_s']:.0f}", med]
        rows.append(" & ".join(cells))
    return table("tab_latency.tex", "Detection rate and time to detection of fault runs at both label-free budgets.",
                 "tab:latency", "l" + "l" * 12,
                 "& \\multicolumn{6}{c}{E-commerce} & \\multicolumn{6}{c}{IoT} \\\\ & \\multicolumn{3}{c}{1\\%} & "
                 "\\multicolumn{3}{c}{5\\%} & \\multicolumn{3}{c}{1\\%} & \\multicolumn{3}{c}{5\\%} \\\\ Detector & "
                 "Det. & RMST & Med. & Det. & RMST & Med. & Det. & RMST & Med. & Det. & RMST & Med.", rows,
                 "140 fault runs per workload (campaigns 2 and 3). Time from the verified onset to the start of the "
                 "first alerted window, censored at the labelled span, Kaplan-Meier. RMST is the restricted mean "
                 "up to 300 s, in seconds. A median of 0 means half the runs alert in their first 30 s window.",
                 inputs, wide=True)


def t_categories(cat, perf, inputs):
    rows = []
    p = perf.set_index(["workload", "detector", "metric"])
    c = cat.set_index(["workload", "variant", "metric"])
    for v in ("broker", "consumer", "flink", "jvm", "no_broker", "no_consumer", "no_flink", "no_jvm"):
        label = ("Only " if not v.startswith("no_") else "Without ") + v.replace("no_", "").replace("jvm", "JVM") \
            .replace("flink", "Flink")
        cells = [label]
        for w in ("ecommerce", "iot"):
            r = c.loc[(w, v, "pooled_auc")]
            cells += [f3(p.loc[(w, f"IF_{v}", "pooled_auc"), "pooled_mean"]),
                      ci(r["diff_pooled"], r["diff_lo"], r["diff_hi"], True)]
        rows.append(" & ".join(cells))
    return table("tab_categories.tex", "Isolation Forest on one telemetry category, or without one, against all "
                 "features.", "tab:categories", "lllll", "& \\multicolumn{2}{c}{E-commerce} & "
                 "\\multicolumn{2}{c}{IoT} \\\\ Features & Pooled AUC & Minus all features & Pooled AUC & "
                 "Minus all features", rows,
                 "Exploratory (RQ3). Pooled over campaigns 2 and 3 with 95\\% intervals of the paired fold "
                 "difference. Frozen Isolation Forest configuration in every variant.", inputs)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--out", required=True)
    p.add_argument("--dest", required=True)
    a = p.parse_args(argv)
    out, dest = Path(a.out), Path(a.dest)
    dest.mkdir(parents=True, exist_ok=True)
    res = json.loads((out / "confirm.json").read_text())
    ph = json.loads((out / "posthoc.json").read_text())
    D = out / "describe"
    perf, oper = pd.read_parquet(D / "performance.parquet"), pd.read_parquet(D / "operating.parquet")
    lat, cat = pd.read_parquet(D / "latency.parquet"), pd.read_parquet(D / "categories.parquet")
    h = lambda *fs: {f: sha256_file(out / f) for f in fs}
    made = [t_confirm(res, h("confirm.json")), t_c1(res, ph, h("confirm.json", "posthoc.json")),
            t_c6(res, h("confirm.json")), t_c7(res, h("confirm.json")),
            *[t_confirm_detail(res, w, h("confirm.json")) for w in ("ecommerce", "iot")],
            *[t_rq1(perf, w, h("describe/performance.parquet")) for w in ("ecommerce", "iot")],
            *[t_oper(oper, b, h("describe/operating.parquet")) for b in ("0.01", "0.05")],
            t_latency(lat, h("describe/latency.parquet")),
            t_categories(cat, perf, h("describe/categories.parquet", "describe/performance.parquet"))]
    for name, text in made:
        (dest / name).write_text(text)
    print(f"tables: {len(made)} files in {dest}")


if __name__ == "__main__":
    main()
