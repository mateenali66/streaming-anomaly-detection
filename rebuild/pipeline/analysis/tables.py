WL = {"ecommerce": "E-commerce", "iot": "IoT"}
CAPTION_MAX = 20


def caption(text: str) -> str:
    n = len(text.split())
    if n > CAPTION_MAX:
        raise SystemExit(f"ERROR: caption of {n} words: {text}")
    return text


def ci(m, lo, hi, signed=False):
    f = s3 if signed else f3
    return f"{tex_num(f(m))} [{tex_num(f(lo))}, {tex_num(f(hi))}]"


def table(name, cap, label, colspec, header, rows, note, inputs, wide=True):
    """Every table spans both columns (table*) and shrinks to the text width only when it is wider (adjustbox)."""
    env = "table*"
    lines = [f"% Generated by analysis/tables.py. Do not edit."]
    lines += [f"% input {k} sha256 {v}" for k, v in sorted(inputs.items())]
    lines += [f"\\begin{{{env}}}[htbp]", "\\centering", "\\footnotesize", f"\\caption{{{caption(cap)}}}",
              f"\\label{{{label}}}", "\\begin{adjustbox}{max width=\\textwidth}",
              f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", header + " \\\\", "\\midrule"]
    lines += [r + " \\\\" if r != "\\midrule" else r for r in rows]
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{adjustbox}",
              f"\\par\\smallskip\\parbox{{\\linewidth}}{{\\scriptsize {note}}}",
              f"\\end{{{env}}}"]
    return name, "\n".join(lines) + "\n"


def t_confirm(res, inputs):
    rows = []
    for h, desc in (("C1", "Deep models vs max-z"), ("C2a", "EWMA vs max-z"), ("C2b", "EWMA fixed vs mean centre"),
                    ("C3", "Sequence vs point models"), ("C4", "Category fusion vs IF"), ("C5", "Fault-difficulty transfer"),
                    ("C6", "Within vs cross workload")):
        cells = [h, desc]
        for w in ("ecommerce", "iot"):
            W = res["workloads"][w]
            out = (("superior" if W["C5_superior"] else "not significant") if h == "C5"
                   else W["hypotheses"][h]["outcome"])
            cells += [out.replace("model beats max-z: ", "beats max-z: "), tex_num(pfmt(W["family_p"][h])),
                      tex_num(pfmt(W["family_p_holm"][h]))]
        rows.append(" & ".join(cells))
    n_rep = sum(v["reproducible"] for D in res["C7"].values() for v in D.values())
    n_all = sum(len(D) for D in res["C7"].values())
    rows.append(f"C7 & Reproducible within $\\Delta$ & \\multicolumn{{6}}{{l}}{{{n_rep} of {n_all} detector and "
                f"workload pairs}}")
    return table("tab_confirm_summary.tex", "Confirmatory hypotheses C1 to C7: outcomes, family p and Holm-adjusted p.",
                 "tab:confirm", "llllllll",
                 "& & \\multicolumn{3}{c}{E-commerce} & \\multicolumn{3}{c}{IoT} \\\\ ID & Contrast & Outcome & $p$ & "
                 "Holm $p$ & Outcome & $p$ & Holm $p$", rows,
                 "Pooled over campaigns 2 and 3, ten folds each, margin $\\Delta=0.03$ AUC. Holm runs over the seven "
                 "hypotheses of each workload (D4). Each $p$ is that of the hypothesis's superiority test. C5 is one "
                 "test across both workloads.", inputs, wide=True)


def t_c1(res, ph, inputs):
    rows = []
    for m in DEEP + ["EWMA"]:
        cells = [NAMES[m]]
        for w in ("ecommerce", "iot"):
            H = res["workloads"][w]["hypotheses"]
            if m == "EWMA":
                a, b = H["C2a"]["contrasts"]["pooled_auc"], H["C2a"]["contrasts"]["within_run_pc"]
            else:
                a, b = H["C1"]["contrasts"][f"{m}|pooled_auc"], H["C1"]["contrasts"][f"{m}|within_run_pc"]
            c = ph["within_run"][w]["C1_within_run_auc"][m]["pooled"]
            cells += [ci(a["pooled"]["mean"], a["pooled"]["ci95_lo"], a["pooled"]["ci95_hi"], True),
                      ci(b["pooled"]["mean"], b["pooled"]["ci95_lo"], b["pooled"]["ci95_hi"], True),
                      ci(c["mean"], c["ci95_lo"], c["ci95_hi"], True)]
        rows.append(" & ".join(cells))
    return table("tab_c1.tex", "Each deep model and EWMA minus static max-z, by AUC metric.", "tab:c1", "lllllll",
                 "& \\multicolumn{3}{c}{E-commerce} & \\multicolumn{3}{c}{IoT} \\\\ Detector & Pooled & "
                 "Within-run, corrected & Within-run, plain$^{a}$ & Pooled & Within-run, corrected & "
                 "Within-run, plain$^{a}$", rows,
                 "Mean paired difference in AUC with 95\\% interval, pooled over campaigns 2 and 3 (20 folds). "
                 "Corrected subtracts each fold's sham placebo (C1, C2a). $^{a}$Post hoc (D5), not a confirmatory "
                 "test.", inputs, wide=True)


def t_confirm_detail(res, w, inputs):
    """Per-campaign statistics behind each confirmatory contrast (protocol 5.2, 5.3): BCa interval, exact Wilcoxon p
    and rank-biserial r per confirmatory campaign, the sign-flip p and the random-effects tau and ICC of the pool."""
    W = res["workloads"][w]
    cs = ["ec-b", "ec-c"] if w == "ecommerce" else ["iot-b", "iot-c"]
    rows = []
    order = [("C1", f"{m}|{k}", f"C1 {NAMES[m]}, {lab}") for m in DEEP for k, lab in
             (("pooled_auc", "pooled"), ("within_run_pc", "corrected"))]
    order += [("C2a", "pooled_auc", "C2a pooled"), ("C2a", "within_run_pc", "C2a corrected"),
              ("C2b", "pooled_auc", "C2b pooled"), ("C3", "pooled_auc_matched", "C3 pooled, matched"),
              ("C3", "within_run_pc", "C3 corrected"), ("C4", "pooled_auc", "C4 pooled")]
    order += [("C6", m, f"C6 {NAMES[m]}") for m in PANEL]
    for h, key, label in order:
        r = W["hypotheses"][h]["contrasts"][key]
        cells = [label]
        for c in cs:
            v = r["per_campaign"][c]
            cells += [ci(v["mean"], v["bca95_lo"], v["bca95_hi"], True), tex_num(pfmt(v["p_wilcoxon"])),
                      f"{v['rank_biserial']:+.2f}".replace("-", "$-$")]
        re_ = r["random_effects"]
        cells += [tex_num(pfmt(r["sign_flip"]["p_sign_flip"])), f"{re_['tau']:.3f}",
                  "0 (singular)" if re_["singular"] else f"{re_['icc']:.2f}"]
        rows.append(" & ".join(cells))
    lab = {"ecommerce": "E-commerce", "iot": "IoT"}[w]
    return table(f"tab_confirm_detail_{w}.tex", f"{lab} confirmatory contrasts: statistics per campaign and for the pool.",
                 f"tab:confirm-detail-{w}", "l" + "l" * 9,
                 f"& \\multicolumn{{3}}{{c}}{{Campaign 2 ({cs[0]})}} & \\multicolumn{{3}}{{c}}{{Campaign 3 ({cs[1]})}} & "
                 "\\multicolumn{3}{c}{Pooled} \\\\ Contrast & Mean [BCa 95\\%] & Wilcoxon $p$ & $r_{rb}$ & "
                 "Mean [BCa 95\\%] & Wilcoxon $p$ & $r_{rb}$ & Sign-flip $p$ & $\\tau$ & ICC", rows,
                 "Ten folds per campaign. Exact two-sided Wilcoxon signed-rank $p$ and matched-pairs rank-biserial "
                 "correlation per campaign. The sign-flip $p$ is exact over all $2^{20}$ vectors. $\\tau$ and the ICC "
                 "come from the one-way REML estimate, singular when $\\tau$ is 0. Corrected is placebo-corrected "
                 "within-run AUC.", inputs, wide=True)


