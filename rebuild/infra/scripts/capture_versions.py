#!/usr/bin/env python3
"""Capture the EKS add-on versions and the node AMI release for one Kubernetes version and write an .auto.tfvars file.

Reads AWS (EKS describe_addon_versions, EKS describe_addon_configuration, SSM get_parameter). Writes only the output file. boto3.
No account ID, profile name or e-mail goes into the file.

  python3 scripts/capture_versions.py --kubernetes-version 1.35 --out terraform/cluster/addon-versions.auto.tfvars

Add-on version rule (--select): `default` picks the version AWS marks as the default for that Kubernetes version, `latest` picks the
newest listed. Default: `default`. The AMI release comes from
  /aws/service/eks/optimized-ami/<k8s>/amazon-linux-2023/arm64/standard/recommended/release_version
Run it ONCE, commit the file, and every campaign cluster uses the same versions (REVIEW3 A3, protocol 1.7 item 1).

--check-config also reads each add-on's configuration schema and fails if the keys that terraform/cluster/main.tf sets
(coredns tolerations and nodeSelector; ebs-csi controller.extraVolumeTags, tolerations and nodeSelector) are not in it, so a
wrong configuration_values is found now and not as a failed cluster create.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

import boto3

ADDONS = ["coredns", "kube-proxy", "vpc-cni", "eks-pod-identity-agent", "aws-ebs-csi-driver"]
CONFIG_KEYS = {
    "coredns": [("tolerations",), ("nodeSelector",)],
    "aws-ebs-csi-driver": [("controller", "extraVolumeTags"), ("controller", "tolerations"), ("controller", "nodeSelector")],
}


def pick_version(eks, addon: str, k8s: str, select: str) -> str:
    versions: list[dict] = []
    token = None
    while True:
        kw = {"kubernetesVersion": k8s, "addonName": addon}
        if token:
            kw["nextToken"] = token
        resp = eks.describe_addon_versions(**kw)
        for a in resp.get("addons", []):
            versions.extend(a.get("addonVersions", []))
        token = resp.get("nextToken")
        if not token:
            break
    if not versions:
        raise SystemExit(f"no versions of {addon} for Kubernetes {k8s}")
    if select == "default":
        for v in versions:
            if any(c.get("clusterVersion") == k8s and c.get("defaultVersion") for c in v.get("compatibilities", [])):
                return v["addonVersion"]
        raise SystemExit(f"{addon}: AWS marks no default version for Kubernetes {k8s}; use --select latest")
    return versions[0]["addonVersion"]  # the API lists newest first


def ami_release(ssm, k8s: str) -> str:
    name = f"/aws/service/eks/optimized-ami/{k8s}/amazon-linux-2023/arm64/standard/recommended/release_version"
    return ssm.get_parameter(Name=name)["Parameter"]["Value"]


def _resolve(schema: dict, node: dict) -> dict:
    # Follow local references (`#/definitions/Coredns`). The CoreDNS schema keeps every key behind one at its root.
    seen = 0
    while isinstance(node, dict) and isinstance(node.get("$ref"), str) and node["$ref"].startswith("#/") and seen < 16:
        target = schema
        for part in node["$ref"][2:].split("/"):
            target = target.get(part, {}) if isinstance(target, dict) else {}
        node, seen = target, seen + 1
    return node if isinstance(node, dict) else {}


def has_path(schema: dict, path: tuple[str, ...]) -> bool:
    node = _resolve(schema, schema)
    for p in path:
        node = node.get("properties", {}).get(p)
        if node is None:
            return False
        node = _resolve(schema, node)
    return True


def check_config(eks, addon: str, version: str) -> list[str]:
    if addon not in CONFIG_KEYS:
        return []
    raw = eks.describe_addon_configuration(addonName=addon, addonVersion=version)["configurationSchema"]
    schema = json.loads(raw)
    return [".".join(p) for p in CONFIG_KEYS[addon] if not has_path(schema, p)]


def render(k8s: str, region: str, ami: str, versions: dict[str, str], now: dt.datetime) -> str:
    lines = [
        "# GENERATED by scripts/capture_versions.py. Commit this file. Do not edit by hand.",
        f"# kubernetes {k8s}, region {region}, captured {now.strftime('%Y-%m-%dT%H:%M:%SZ')}",
        f'node_ami_release_version = "{ami}"',
        "addon_versions = {",
    ]
    width = max(len(k) for k in versions) + 2
    for k in sorted(versions):
        lines.append(f'  {json.dumps(k):<{width}} = "{versions[k]}"')
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--kubernetes-version", default="1.35")
    ap.add_argument("--region", default="us-east-2")
    ap.add_argument("--profile", default=None, help="optional; prefer exporting AWS_PROFILE")
    ap.add_argument("--select", choices=["default", "latest"], default="default")
    ap.add_argument("--check-config", action="store_true")
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    s = boto3.Session(profile_name=a.profile, region_name=a.region)
    eks, ssm = s.client("eks"), s.client("ssm")
    versions = {n: pick_version(eks, n, a.kubernetes_version, a.select) for n in ADDONS}
    ami = ami_release(ssm, a.kubernetes_version)
    if not ami.startswith(a.kubernetes_version + "."):
        raise SystemExit(f"AMI release {ami!r} does not belong to Kubernetes {a.kubernetes_version}")
    if a.check_config:
        bad = {n: m for n in ADDONS if (m := check_config(eks, n, versions[n]))}
        if bad:
            raise SystemExit(f"configuration schema is missing keys that main.tf sets: {bad}")
    a.out.write_text(render(a.kubernetes_version, a.region, ami, versions, dt.datetime.now(dt.timezone.utc)))
    for n in ADDONS:
        print(f"{n:<24} {versions[n]}")
    print(f"{'node AMI release':<24} {ami}\nwrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
