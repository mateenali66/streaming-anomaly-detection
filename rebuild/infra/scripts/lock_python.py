#!/usr/bin/env python3
"""Make a fully pinned, hash-checked requirements.lock for a linux/aarch64 CPython 3.12 image from a requirements.in.

  1. `pip download --only-binary=:all:` for the target platform resolves the whole dependency closure (versions).
  2. Every pinned (name, version) is looked up on PyPI and ALL wheel hashes that could be installed on linux/aarch64 cp312 are
     written, so the image build (`pip install --require-hashes --only-binary=:all:`) accepts any compatible wheel of that
     exact version and nothing else.
Run it on any machine with network access; it does not need Docker or an arm64 host. Re-run only to change a pin on purpose.

  scripts/lock_python.py images/orchestrator/requirements.in > images/orchestrator/requirements.lock
Standard library, and a pip that supports `download --platform`.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

PLATFORMS = ["manylinux2014_aarch64", "manylinux_2_17_aarch64", "manylinux_2_28_aarch64", "manylinux_2_26_aarch64", "manylinux_2_24_aarch64", "any"]


def closure(req_in: Path) -> dict[str, str]:
    with tempfile.TemporaryDirectory() as d:
        cmd = [sys.executable, "-m", "pip", "download", "-q", "-d", d, "--only-binary=:all:", "--python-version", "3.12", "--implementation", "cp"]
        for p in PLATFORMS:
            cmd += ["--platform", p]
        cmd += ["-r", str(req_in)]
        subprocess.run(cmd, check=True)
        out: dict[str, str] = {}
        for f in Path(d).glob("*.whl"):
            name, version = f.name.split("-")[:2]
            out[re.sub(r"[-_.]+", "-", name).lower()] = version
        return out


def wheel_hashes(name: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as r:
        files = json.load(r)["urls"]
    keep = []
    for f in files:
        fn = f["filename"]
        if not fn.endswith(".whl"):
            continue
        if "-none-any.whl" in fn or (("aarch64" in fn) and ("-cp312-cp312-" in fn or "-abi3-" in fn)):
            keep.append(f["digests"]["sha256"])
    if not keep:
        raise SystemExit(f"{name}=={version}: no wheel for linux/aarch64 cp312")
    return sorted(set(keep))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("requirements_in", type=Path)
    a = ap.parse_args()
    print(f"# Generated by scripts/lock_python.py from {a.requirements_in.name} for linux/aarch64 CPython 3.12. Do not edit.")
    print("# Install with: pip install --no-cache-dir --require-hashes --only-binary=:all: -r requirements.lock")
    for name, version in sorted(closure(a.requirements_in).items()):
        hashes = wheel_hashes(name, version)
        print(f"{name}=={version} \\")
        print(" \\\n".join(f"    --hash=sha256:{h}" for h in hashes))
    return 0


if __name__ == "__main__":
    sys.exit(main())
